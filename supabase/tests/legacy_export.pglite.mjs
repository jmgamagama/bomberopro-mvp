import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
import { strict as assert } from 'node:assert';
const { PGlite } = createRequire(import.meta.url)('@electric-sql/pglite');
const read = name => readFileSync(new URL('../migrations/'+name,import.meta.url),'utf8');
const db = new PGlite();
await db.exec(`
 create role anon; create role authenticated;
 create function public.get_preparer_session_questions(p_limit int default 10) returns int language sql security definer as $$select 9786$$;
 create function public.unrelated_study() returns int language sql as $$select 1$$;
 revoke execute on function public.get_preparer_session_questions(int) from public,anon;
 grant execute on function public.get_preparer_session_questions(int) to authenticated;
`);
const can = async role => (await db.query("select has_function_privilege($1,'public.get_preparer_session_questions(integer)','execute') allowed",[role])).rows[0].allowed;
assert.equal(await can('authenticated'),true);
await db.exec(read('26_close_legacy_preparer_export.sql'));
assert.equal(await can('authenticated'),false);
assert.equal(await can('anon'),false);
await db.exec('set role authenticated');
await assert.rejects(db.query('select * from get_preparer_session_questions(NULL)'),e=>e.code==='42501');
assert.equal((await db.query('select unrelated_study() n')).rows[0].n,1);
await db.exec('reset role');
assert.equal((await db.query('select get_preparer_session_questions(NULL) n')).rows[0].n,9786,'owner still able');
await db.exec(read('26_close_legacy_preparer_export.sql'));
await db.exec(read('26_close_legacy_preparer_export_down.sql'));
assert.equal(await can('authenticated'),true);
assert.equal(await can('anon'),false);
await db.exec('drop function public.get_preparer_session_questions(integer)');
await db.exec(read('26_close_legacy_preparer_export.sql'));
